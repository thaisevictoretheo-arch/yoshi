export async function fetchCitiesForState(uf: string): Promise<string[]> {
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 2500);
    const response = await fetch(`https://servicodados.ibge.gov.br/api/v1/localidades/estados/${uf}/municipios`, {
      signal: controller.signal
    });
    clearTimeout(timeoutId);

    if (response.ok) {
      const data = await response.json();
      if (Array.isArray(data) && data.length > 0) {
        return data.map((item: any) => item.nome).sort();
      }
    }
  } catch {
    // Graceful fallback on network timeout or CORS issue
  }

  return FALLBACK_CITIES_BY_UF[uf] || ['Capital', 'Região Central'];
}

export function buildGoogleMapsSearchUrl(niche: string, city: string, uf: string): string {
  const query = `${niche} ${city} ${uf} Brasil`;
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`;
}
